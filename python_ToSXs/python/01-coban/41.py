one = 9
two = 3

zsum = one + two
zsub = one - two
zmulti = one * two
zdiv = one / two
zmodulo = one % two

print(f"{one} + {two} = {zsum}")
print(f"{one} - {two} = {zsub}")
print(f"{one} x {two} = {zmulti}")
print('{0} : {1} = {2:.2f}'.format(one, two, zdiv))
print(f"{one} % {two} = {zmodulo}")
